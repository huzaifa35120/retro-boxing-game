const FONT = {};
const FONT_ORDER = [];
for (const ch in FONT_SRC) {
  FONT[ch] = FONT_SRC[ch].split('/').map(r => parseInt(r.replace(/\./g, '0').replace(/#/g, '1'), 2));
  FONT_ORDER.push(ch);
}
const FONT_INDEX = {};
FONT_ORDER.forEach((c, i) => { FONT_INDEX[c] = i; });

function textW(s) { return s.length * FONT_ADV; }

/* One little canvas per colour, holding every glyph in a row. Drawing a
   string is then one drawImage per character. */
const FONT_ATLAS = new Map();

function fontAtlas(col) {
  let a = FONT_ATLAS.get(col);
  if (a) return a;
  a = document.createElement('canvas');
  a.width = FONT_ORDER.length * FONT_ADV;
  a.height = FONT_H;
  const c = a.getContext('2d');
  c.fillStyle = col;
  FONT_ORDER.forEach((ch, i) => {
    const g = FONT[ch];
    for (let r = 0; r < FONT_H; r++) {
      let run = 0;
      for (let b = 0; b <= FONT_W; b++) {
        const on = b < FONT_W && (g[r] & (1 << (FONT_W - 1 - b)));
        if (on) run++;
        else if (run) { c.fillRect(i * FONT_ADV + b - run, r, run, 1); run = 0; }
      }
    }
  });
  FONT_ATLAS.set(col, a);
  return a;
}

function drawText(ctx, s, x, y, col) {
  const a = fontAtlas(col);
  x = Math.round(x); y = Math.round(y);
  for (let i = 0; i < s.length; i++) {
    let ch = s[i];
    if (FONT_INDEX[ch] === undefined) ch = ch.toUpperCase();
    const idx = FONT_INDEX[ch];
    if (idx === undefined || ch === ' ') continue;
    ctx.drawImage(a, idx * FONT_ADV, 0, FONT_W, FONT_H,
                  x + i * FONT_ADV, y, FONT_W, FONT_H);
  }
}
